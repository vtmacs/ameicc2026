  function applyLang(lang) {
    if (lang !== 'ja') {
      // English is the default content in HTML; reset if previously translated
      document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (translations.en && translations.en[key]) {
          el.innerHTML = translations.en[key];
        } else if (el.dataset.defaultContent) {
          el.innerHTML = el.dataset.defaultContent;
        }
      });
    } else {
      document.querySelectorAll('[data-i18n]').forEach(el => {
        const key = el.getAttribute('data-i18n');
        if (!el.dataset.defaultContent) el.dataset.defaultContent = el.innerHTML;
        const dict = translations[lang] || {};
        if (dict[key]) {
          el.innerHTML = dict[key];
        }
      });
    }
    document.querySelectorAll('[data-i18n-title]').forEach(el => {
      const key = el.getAttribute('data-i18n-title');
      if (!el.dataset.defaultTitle) el.dataset.defaultTitle = el.title;
      if (lang === 'en') {
        el.title = el.dataset.defaultTitle;
      } else {
        const dict = translations[lang] || {};
        if (dict[key]) el.title = dict[key];
      }
    });
    document.documentElement.lang = lang === 'ja' ? 'ja' : 'en';
    localStorage.setItem('site-lang', lang);
    const select = document.getElementById('lang-switcher');
    if (select) select.value = lang;
  }

  document.addEventListener('DOMContentLoaded', () => {
    const saved = localStorage.getItem('site-lang') || 'en';
    applyLang(saved);

    const select = document.getElementById('lang-switcher');
    if (select) {
      select.addEventListener('change', e => applyLang(e.target.value));
    }

    // Editable content in code blocks
    document.querySelectorAll('.edit-input').forEach(input => {
      const target = input.dataset.target;
      const escapeJson = str => str.replace(/\\/g, '\\\\').replace(/"/g, '\\"');
      const update = () => {
        const escaped = escapeJson(input.value);
        document.querySelectorAll(`.editable-content[data-target="${target}"]`).forEach(span => {
          span.textContent = escaped;
        });
      };
      input.addEventListener('input', update);
      update();
    });

    // Copy buttons
    document.querySelectorAll('.copy-btn').forEach(btn => {
      btn.addEventListener('click', () => {
        const code = btn.parentElement.querySelector('code');
        if (!code) return;
        let text = code.textContent;
        const token = localStorage.getItem('ai-engine-token');
        if (token) {
          text = text.replace(/\$\{AI_ENGINE_TOKEN\}/g, token);
        }
        navigator.clipboard.writeText(text).then(() => {
          const original = btn.textContent;
          const ok = btn.getAttribute('data-i18n') === 'common.copy' ? 'Copied!' : 'Copied!';
          btn.textContent = ok;
          setTimeout(() => { btn.textContent = original; }, 1200);
        });
      });
    });

    // Account token input (saved in browser for reuse across modules)
    const tokenInput = document.getElementById('account-token');
    if (tokenInput) {
      const savedToken = localStorage.getItem('ai-engine-token');
      if (savedToken) tokenInput.value = savedToken;
      tokenInput.addEventListener('input', () => {
        localStorage.setItem('ai-engine-token', tokenInput.value);
      });
    }

    // Worksheet autosave
    document.querySelectorAll('[data-worksheet]').forEach(field => {
      const key = 'ws-' + field.getAttribute('data-worksheet');
      const savedVal = localStorage.getItem(key);
      if (savedVal) field.value = savedVal;
      field.addEventListener('input', () => localStorage.setItem(key, field.value));
    });
  });
